using System.Text;

namespace dottype;

internal static class CSharpWriter
{
    public static string Write(PocoSchema schema, string? namespaceName)
    {
        var result = new StringBuilder();
        result.AppendLine("// <auto-generated by dottype>");
        result.AppendLine("#nullable enable");
        result.AppendLine();

        if (namespaceName is not null)
        {
            result.Append("namespace ").Append(namespaceName).AppendLine(";");
            result.AppendLine();
        }

        foreach (PocoClass pocoClass in schema.Classes)
        {
            result.Append("public partial class ").Append(pocoClass.Name).AppendLine();
            result.AppendLine("{");
            foreach (PocoProperty property in pocoClass.Properties)
            {
                bool changed = Identifier.Unescaped(property.Name) != property.SourceName;
                if (changed)
                {
                    string sourceName = EscapeString(property.SourceName);
                    result.Append("    [global::System.Runtime.Serialization.DataMember(Name = \"")
                        .Append(sourceName).AppendLine("\")]");
                    result.Append("    [global::System.Text.Json.Serialization.JsonPropertyName(\"")
                        .Append(sourceName).AppendLine("\")]");
                }

                string nullability = property.IsNullable ? "?" : "";
                result.Append("    public ").Append(property.TypeName).Append(nullability).Append(' ')
                    .Append(property.Name).Append(" { get; set; }");
                if (!property.IsValueType && !property.IsNullable)
                {
                    result.Append(" = default!;");
                }
                result.AppendLine();
                result.AppendLine();
            }
            result.AppendLine("}");
            result.AppendLine();
        }

        return result.ToString();
    }

    private static string EscapeString(string value)
    {
        var result = new StringBuilder(value.Length);
        foreach (char character in value)
        {
            result.Append(character switch
            {
                '\\' => "\\\\",
                '\"' => "\\\"",
                '\r' => "\\r",
                '\n' => "\\n",
                '\t' => "\\t",
                '\0' => "\\0",
                _ when char.IsControl(character) || char.IsSurrogate(character) || character is '\u2028' or '\u2029' => $"\\u{(int)character:x4}",
                _ => character.ToString()
            });
        }
        return result.ToString();
    }
}
