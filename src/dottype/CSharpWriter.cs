using System.Text;

namespace dottype;

internal static class CSharpWriter
{
    public static string Write(PocoSchema schema, string? namespaceName, bool csvHelperMap = false)
    {
        var result = new StringBuilder();
        result.AppendLine("// <auto-generated by dottype>");
        result.AppendLine("#nullable enable");
        result.AppendLine();

        if (namespaceName is not null)
        {
            result.Append("namespace ").Append(namespaceName).AppendLine(";");
            result.AppendLine();
        }

        PocoClass root = schema.Classes[0];
        if (schema.NestChildTypes)
            WriteClass(result, root, "", schema.Classes.Skip(1));
        else
            foreach (PocoClass poco in schema.Classes) WriteClass(result, poco, "");
        if (csvHelperMap) WriteCsvHelperMap(result, root);
        return result.ToString();
    }

    private static void WriteClass(StringBuilder result, PocoClass pocoClass, string classIndent, IEnumerable<PocoClass>? children = null)
    {
        result.Append(classIndent).Append(classIndent.Length == 0 ? "public " : MemberModifiers(pocoClass.Name))
            .Append("partial class ").AppendLine(pocoClass.Name);
        result.Append(classIndent).AppendLine("{");
        string indent = classIndent + "    ";
        foreach (PocoProperty property in pocoClass.Properties)
        {
            bool changed = Identifier.Unescaped(property.Name) != property.SourceName;
            if (changed)
            {
                string sourceName = EscapeString(property.SourceName);
                result.Append(indent).Append("[global::System.Runtime.Serialization.DataMember(Name = \"")
                    .Append(sourceName).AppendLine("\")]");
                result.Append(indent).Append("[global::System.Text.Json.Serialization.JsonPropertyName(\"")
                    .Append(sourceName).AppendLine("\")]");
            }

            string nullability = property.IsNullable ? "?" : "";
            result.Append(indent).Append(MemberModifiers(property.Name)).Append(property.TypeName).Append(nullability).Append(' ')
                .Append(property.Name).Append(" { get; set; }");
            if (!property.IsValueType && !property.IsNullable)
            {
                result.Append(" = default!;");
            }
            result.AppendLine();
            result.AppendLine();
        }
        if (children is not null)
            foreach (PocoClass child in children) WriteClass(result, child, indent);
        result.Append(classIndent).AppendLine("}");
        result.AppendLine();
    }

    private static string MemberModifiers(string name) => Identifier.Unescaped(name) is
        "ToString" or "GetHashCode" or "Equals" or "GetType" or "MemberwiseClone" or "ReferenceEquals" ? "public new " : "public ";

    private static void WriteCsvHelperMap(StringBuilder result, PocoClass row)
    {
        string mapName = Identifier.Unescaped(row.Name) + "Map";
        result.Append("public sealed class ").Append(mapName)
            .Append(" : global::CsvHelper.Configuration.ClassMap<").Append(row.Name).AppendLine(">");
        result.AppendLine("{");
        result.Append("    public ").Append(mapName).AppendLine("()");
        result.AppendLine("    {");
        foreach (PocoProperty property in row.Properties)
        {
            result.Append("        Map(row => row.").Append(property.Name).Append(").Name(\"")
                .Append(EscapeString(property.SourceName)).Append("\")");
            // CSV inference accepts exponent notation (including for decimal).
            if (property.TypeName is "decimal" or "double")
                result.Append(".TypeConverterOption.NumberStyles(global::System.Globalization.NumberStyles.Float)");
            result.AppendLine(";");
        }
        result.AppendLine("    }");
        result.AppendLine("}");
    }

    private static string EscapeString(string value)
    {
        var result = new StringBuilder(value.Length);
        foreach (char character in value)
        {
            result.Append(character switch
            {
                '\\' => "\\\\",
                '\"' => "\\\"",
                '\r' => "\\r",
                '\n' => "\\n",
                '\t' => "\\t",
                '\0' => "\\0",
                _ when char.IsControl(character) || char.IsSurrogate(character) || character is '\u2028' or '\u2029' => $"\\u{(int)character:x4}",
                _ => character.ToString()
            });
        }
        return result.ToString();
    }
}
